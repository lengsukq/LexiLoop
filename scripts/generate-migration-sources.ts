import fs from "node:fs";
import path from "node:path";

const directory = path.join(process.cwd(), "src", "db", "migrations");
const files = fs.readdirSync(directory).filter((file) => file.endsWith(".sql")).sort();
const migrations = files.map((name) => ({ name, sql: fs.readFileSync(path.join(directory, name), "utf8") }));
const output = `// Generated by scripts/generate-migration-sources.ts. Do not edit manually.\nexport const MIGRATIONS = ${JSON.stringify(migrations, null, 2)} as const;\n`;
fs.writeFileSync(path.join(process.cwd(), "src", "db", "migration-sources.ts"), output);
console.log(`[LexiLoop] generated ${migrations.length} migration source(s)`);
